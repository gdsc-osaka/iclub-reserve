import { Link } from "react-router";

/**
 * 有効な団体に所属していないので、予約を申請できない人への説明（COND-006）。
 *
 * 空き状況カレンダー（SCR-001）と申請フォーム（SCR-002）の両方で同じ文を出す。
 * どちらかだけ直して言うことが食い違わないように、ここに 1 つだけ置く。
 *
 * まだどの団体にも入っていない人と、団体が承認待ちの人とで、次にすることが違う。
 * どちらに当たるかはここでは調べていないので、両方の場合を書いておく。
 * 団体に入るには、自分で登録するか、団体の管理者から招待を受けるしかない。
 */
export function NoEnabledGroupReason() {
  return (
    <>
      予約を申請できるのは、事務局が有効にした団体のメンバーだけです。まだ団体に所属していない場合は、
      <Link to="/groups/new">団体を登録する</Link>
      か、団体の管理者に招待してもらってください。所属している団体が承認待ちの場合は、承認されるまでお待ちください。
    </>
  );
}
